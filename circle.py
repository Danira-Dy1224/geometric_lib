import math;

def area(r):
    '''
    Принимает значение r, где r (int) - радиус окружности
    Возвращает площадь окружности (float)
    '''
    return math.pi * r * r


def perimeter(r):
    '''
    Принимает значение r, где r (int) - радиус окружности
    Возвращает длину окружности (float)
    '''
    return 2 * math.pi * r

